def calculator(a,b,მათემატიკური_ოპერატორი):
    if მათემატიკური_ოპერატორი=="+":
        print(a+b)
    elif მათემატიკური_ოპერატორი=="-":
        print(a-b)
    elif მათემატიკური_ოპერატორი=="*":
        print(a*b)
    elif მათემატიკური_ოპერატორი=="/":
        print(a/b)
